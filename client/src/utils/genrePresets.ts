/**
 * 合并题材：服务端有数据时严格以服务端为准，防止管理端删除的预设被内置常量补回；
 * 仅在接口降级（系统预设为空）或失败时才用内置预设兜底。
 */
export function mergeGenres(remote: GenreItem[], degraded = false): GenreItem[] {
  if (!degraded && remote.length) return [...remote]
  const seen = new Set(remote.map((item) => item.name))
  return [...remote, ...GENRE_PRESETS.filter((item) => !seen.has(item.name))]
}
