def decompose_guide():
    """拆解（参考生成 / 已有大纲两模式共用）：写作公式视角的提炼要求。"""
    return (compose("framework", "conflict", "payoff", "foreshadow", "character")
            + """

落实到输出（在以上规则基础上追加）：
1. 每章 summary 体现它处于框架五段的哪个阶段、主要推进哪条剧情线（主线 / 辅线 / 事件线 / 感情线）。
2. 每章 conflict 先写清「谁与谁 / 什么对抗」，末尾用七式之一标注冲突类型（内心 / 人际 / 环境 / 时间 / 道德 / 信念 / 信息）。
3. payoff 标注爽点类型（打脸 / 逆袭 / 反转 / 情感爽 / 结果爽）；setup 写清埋设物（哪件东西、哪句话、哪个人），便于后文呼应回收。
4. 人物卡体现人物公式：动机（核心欲望 + 阻碍 + 代价）写进 goal，成长线（过去缺陷 → 克服困难 → 改变）写进背景或性格，出场要有记忆点。""")


def adapt_guide(kind):
    """改编流程的追加要求。kind：book（书级）/ chapter（逐章与映射共用）/ plan（章数规划）/ sequel（续写）。"""
    if kind == "book":
        return ("人物与元素搭配（追加要求）：\n"
                + compose("character", "elements")
                + "\n落实：新人物卡保留原著的动机公式（核心欲望 + 阻碍 + 代价）与成长线结构，"
                  "只换世界观下的身份与措辞；主角 / 反派 / 感情线元素搭配完整，关系须带「需求 + 影响 + 冲突」。")
    if kind == "plan":
        return ("章节映射（追加要求）：\n"
                + compose("plot")
                + "\n落实：原著的高潮章与爽点兑现章优先保留为独立新章，不得被合并吞掉；"
                  "映射后的新章序列仍要读得出五段式节奏（开端 / 起承 / 发展 / 高潮 / 结尾），"
                  "note 里注明该新章处于哪个阶段。")
    if kind == "sequel":
        return ("续写新剧情（追加要求）：\n"
                + compose("conflict", "foreshadow", "ending")
                + "\n落实：承接上文未回收的伏笔优先兑现（埋设 → 呼应），新冲突按七式设计且挂在主线上；"
                  "若推进到全书结局，按收束五式之一设计结尾，给读者留下余味。")
    # chapter：逐章改写与映射改编共用
    return ("冲突·节奏·爽点（追加要求）：\n"
            + compose("conflict", "pacing")
            + "\n落实：保留原著每章的冲突类型与爽点兑现节奏——有 payoff 的章不得改成纯过渡章；"
              "章末钩子按其类型（悬念 / 危机 / 反转 / 期待 / 信息差 / 情感）保留或升级；"
              "快慢节奏交替，不要把原著的起伏拉平。")


def storymap_guide():
    """设定图谱 AI 补齐：写作公式视角的抽取要求（追加为第 8 条要求）。"""
    return """8. 写作公式视角（追加）：
   · 关系边优先识别功能性关系——「主角需求 + 影响 + 冲突关系」（需要盟友却遇到背叛者这类）；
     人物卡里已写明的关系照用，不改写。
   · plot.mainline / subplots 按剧情五线划分（主线 / 辅线 / 事件线 / 感情线）；
     plot.foreshadow 条目按「埋设 → 呼应 / 回收」成对书写并注出章号。
   · conflicts 核查时兼顾逻辑线：前期设定与后文转折是否自洽（常识漏洞、因果跳跃）。"""


def expand_note(mode, first_chapter=False):
    """正文生成各模式的追加指引（整章与选区共用一套 mode 语义）。

    mode：outline / continue / expand / rewrite / polish。
    first_chapter：本章为第 1 章时追加开篇公式指引。
    """
    if mode == "outline":
        note = compose("pacing", "payoff")
        if first_chapter:
            opening = get("opening")
            note = (opening + "\n落实：本章是第 1 章——按上面选定的一种开篇公式切入，"
                    "前几百字内抛出核心钩子（疑问、冲突或反差），不要从空洞的天气与身世介绍写起。\n\n" + note) \
                if opening else note
        return note + "\n落实：本章按节奏控制安排快慢交替，爽点按题材兑现，压抑与释放成对出现。"
    if mode == "continue":
        return (compose("foreshadow", "pacing")
                + "\n落实：承接前文已埋的伏笔，该呼应的在本章呼应；节奏与上一章交替，"
                  "上一章是爆发章则本章允许放缓铺垫，但章末仍要留钩。")
    if mode == "expand":
        return (compose("technique", "scene", "dialogue")
                + "\n落实：扩写优先把概括叙述展开成六类技巧的具体描写；环境按四式服务情绪，"
                  "对话按六式写出性格与潜台词。")
    if mode == "rewrite":
        return (compose("dialogue", "pacing")
                + "\n落实：重写时对话按六式赋予性格与潜台词，叙述节奏长短交替、强弱冲突交替，"
                  "不要把原文的起伏抹平。")
    if mode == "polish":
        return (get("technique")
                + "\n落实：打磨时顺手修正「描写无目的性」的句子——与剧情和塑造无关的描写删，"
                  "该有感官 / 动作落地的概括句补具体。")
    return ""


def review_note(kind):
    """审查各检查项的追加评估维度。kind：theme / consistency / foreshadow / advice / ai_taste。"""
    if kind == "theme":
        return ("【追加维度 · 内容框架与五线】\n"
                + compose("framework")
                + "\n判断偏离时对照：本章应推进哪条剧情线（主线 / 辅线 / 事件线 / 感情线）、"
                  "处于框架五段的哪个阶段；既不推进主线也不服务辅线的段落才算游离。")
    if kind == "consistency":
        return ("【追加维度 · 人物公式】\n"
                + get("character")
                + "\n追加比对：角色行为是否服务其动机公式（核心欲望 + 阻碍 + 代价），"
                  "成长线是否被凭空跳跃（没有克服困难的过程就直接改变），"
                  "人物关系是否突然丧失「需求 + 冲突」的功能性。")
    if kind == "foreshadow":
        return ("【追加维度 · 伏笔五式】\n"
                + get("foreshadow")
                + "\n按五式核对：埋设与回收是否成对、回收是否突兀（此前毫无暗示）、"
                  "悬念是否超期未答、对比铺垫是否被后文浪费。")
    if kind == "advice":
        return ("【建议方向锚 · 三大核心公式与自查清单】\n"
                + compose("core3", "checklist")
                + "\n给建议时以上面为方向锚：正向建议指向「困境 / 强冲突 / 满意结局」「动机与成长」"
                  "「期待 / 波动 / 共鸣」中的具体缺口，反向建议点名要避开的写法。")
    if kind == "ai_taste":
        return ("【追加检查维度】\n"
                "13. 描写手法单一：全章只有视觉陈述，没有听觉 / 嗅觉 / 触觉与心理感受的配合\n"
                "14. 对话千人一面：所有角色说话一个腔调，没有性格、语气与潜台词的区分（对应对话六式）\n"
                "15. 描写无目的性：与剧情发展和角色塑造无关的环境 / 外貌 / 心理描写，纯凑字")
    return ""
