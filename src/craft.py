def get(name):
    """取一个公式块：提示词模板库有覆盖用覆盖（键名 craft.<name>），否则用内置默认。"""
    default = DEFAULTS.get(name, "")
    try:
        import studio
        return studio.prompt_override(f"craft.{name}") or default
    except Exception:  # noqa —— studio 损坏 / 缺失时退回内置默认
        return default


def compose(*names):
    """把若干公式块拼成一段注入文本（未知名自动跳过）。"""
    return "\n\n".join(t for t in (get(n) for n in names) if t)


